from django.core.management.base import BaseCommand

from about.models import (
    AboutPage, AboutFeature, AboutCardStat, AboutCounter, AboutValue,
    AboutMilestone, AboutAdvantage, AboutLinkCard,
)


class Command(BaseCommand):
    help = "Заполняет страницу «О нас» тем контентом, который раньше был зашит в шаблоне."

    def handle(self, *args, **options):
        page = AboutPage.load()
        if page.features.exists() or page.values.exists():
            self.stdout.write(self.style.WARNING("Страница уже заполнена — пропускаю."))
            return

        def add(model, rows, fields):
            for i, row in enumerate(rows):
                model.objects.create(page=page, order=i, **dict(zip(fields, row)))

        add(AboutFeature, [
            ("code", "Практика с первого курса", "Лабораторные, мини-проекты и командная разработка вместо чистой теории."),
            ("users", "Опытные преподаватели", "Педагоги и практики из индустрии, которые знают, что нужно на работе."),
            ("briefcase", "Стажировки и трудоустройство", "Сотрудничество с компаниями-партнёрами и поддержка при поиске первой работы."),
        ], ("icon", "title", "text"))

        add(AboutCardStat, [
            ("2023", "год основания"), ("1500+", "студентов"),
            ("8", "программ обучения"), ("50+", "партнёров"),
        ], ("number", "label"))

        add(AboutCounter, [
            ("graduation", 1500, "+", "Студентов обучается"),
            ("users", 80, "+", "Преподавателей"),
            ("grid", 8, "", "Программ обучения"),
            ("briefcase", 50, "+", "Компаний-партнёров"),
        ], ("icon", "value", "suffix", "label"))

        add(AboutValue, [
            ("target", "Наша миссия", "Давать доступное качественное образование в сфере IT и растить специалистов, способных развивать цифровую экономику страны."),
            ("star", "Качество", "Актуальные программы, современное оборудование и регулярное обновление курсов вместе с индустрией."),
            ("pencil", "Практика", "Учимся делать, а не только слушать: проекты, хакатоны и стажировки — часть учебного процесса."),
            ("heart", "Поддержка", "Внимательное отношение к каждому студенту: кураторы, наставники и комфортная среда для учёбы."),
            ("globe", "Открытость", "Сотрудничаем с компаниями, вузами и международными программами, открывая студентам новые возможности."),
            ("trend", "Развитие", "Поощряем любопытство и самостоятельность — чтобы выпускники продолжали учиться и расти всю карьеру."),
        ], ("icon", "title", "text"))

        add(AboutMilestone, [
            ("2023", "Основание колледжа", "Открыт набор на первые IT-программы. Начало работы с первой группой студентов."),
            ("2024", "Расширение программ", "Появились новые направления, запущена электронная система обучения E-bilim, оснащены компьютерные лаборатории."),
            ("2025", "Партнёрства с индустрией", "Заключены соглашения с IT-компаниями о стажировках и совместных проектах."),
            ("2026", "Сегодня", "Молодой и быстрорастущий колледж, который каждый год расширяет набор и учебные программы."),
        ], ("year", "title", "text"))

        add(AboutAdvantage, [
            ("monitor", "Современные лаборатории", "Компьютерные классы с актуальным ПО и оборудованием."),
            ("book", "Актуальные программы", "Учебные планы обновляются вместе с требованиями рынка."),
            ("user", "Наставничество", "Кураторы и менторы сопровождают студентов на всём пути."),
            ("briefcase", "Стажировки", "Практика в компаниях-партнёрах ещё во время учёбы."),
            ("bolt", "Мероприятия и хакатоны", "Конкурсы, олимпиады и встречи с профессионалами отрасли."),
            ("award", "Диплом государственного образца", "Документ, который признают работодатели и вузы."),
        ], ("icon", "title", "text"))

        add(AboutLinkCard, [
            ("user", "Директор", "Обращение директора и стратегия развития колледжа.", "director-url"),
            ("users", "Сотрудники", "Преподаватели и административная команда колледжа.", "sotrudniki-url"),
            ("graduation", "Выпускники", "Истории успеха тех, кто начал карьеру в IT с нашего колледжа.", "graduates-url"),
        ], ("icon", "title", "text", "url_name"))

        self.stdout.write(self.style.SUCCESS("Готово: страница «О нас» заполнена."))
